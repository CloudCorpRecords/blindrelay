'use strict';
/**
 * Local Agent — the ONLY component that ever touches plaintext or the whole
 * master key, and it runs on the user's own machine (loopback UI).
 *
 * Lifecycle of the master key in this process:
 *   setup : generated -> split into 5 Shamir shares (threshold 3) -> the
 *           whole key is WIPED from this process; only its SHA-256
 *           fingerprint is kept, to verify later reconstructions.
 *   run   : shares are fetched (local vault file + two co-signers),
 *           the key is reconstructed IN MEMORY, fingerprint-checked, used,
 *           and wiped again. It is never written to disk whole, never sent
 *           to the host, and never logged.
 *
 * The LLM call is made from here, directly to the provider endpoint
 * (mock by default; a real OpenAI-shaped endpoint via env), so the host
 * platform never routes the key or the prompt.
 *
 * Env: LOCAL_PORT (8765), HOST_URL, COSIGNER_A_URL, COSIGNER_B_URL,
 *      COSIGNER_TOKEN, LLM_MODE (mock|real), LLM_BASE_URL, LLM_MODEL.
 */
const http = require('http');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const shamir = require('./lib/shamir');
const { deriveSessionKey, encryptString, decryptString, fingerprint } = require('./lib/crypto');

const PORT = parseInt(process.env.LOCAL_PORT || '8765', 10);
const HOST_URL = process.env.HOST_URL || 'http://127.0.0.1:8787';
const COSIGNER_A_URL = process.env.COSIGNER_A_URL || 'http://127.0.0.1:8791';
const COSIGNER_B_URL = process.env.COSIGNER_B_URL || 'http://127.0.0.1:8793';
const COSIGNER_TOKEN = process.env.COSIGNER_TOKEN || 'demo-cosigner-token';
const LLM_MODE = process.env.LLM_MODE || 'mock';
const LLM_BASE_URL = process.env.LLM_BASE_URL || 'http://127.0.0.1:8790/v1';
const LLM_MODEL = process.env.LLM_MODEL || 'mock-llm-1';
const VAULT_FILE = path.join(__dirname, 'vault', 'share1.b64');
const BACKUP_FILE = path.join(__dirname, 'vault', 'share5-offline-backup.b64');

const THRESHOLD = 3;
const N_SHARES = 5;

// After setup this holds NO key material — only public/demo metadata.
let state = null; // { runId, keyFingerprint, demoKeyPreview, lastJobId }

async function call(url, method, body, headers = {}) {
  const res = await fetch(url, {
    method,
    headers: { 'content-type': 'application/json', ...headers },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  let json = null;
  try { json = JSON.parse(text); } catch { /* leave null */ }
  return { status: res.status, json, text };
}

async function fetchShares(count) {
  // Share 1: local vault file. Shares 2,3: independent co-signers.
  const shares = [];
  shares.push(shamir.b64decode(fs.readFileSync(VAULT_FILE, 'utf8').trim()));
  const a = await call(`${COSIGNER_A_URL}/release-share`, 'POST', {}, { 'x-cosigner-token': COSIGNER_TOKEN });
  if (a.status !== 200) throw new Error('co-signer A refused to release its share');
  shares.push(shamir.b64decode(a.json.share));
  if (count >= 3) {
    const b = await call(`${COSIGNER_B_URL}/release-share`, 'POST', {}, { 'x-cosigner-token': COSIGNER_TOKEN });
    if (b.status !== 200) throw new Error('co-signer B refused to release its share');
    shares.push(shamir.b64decode(b.json.share));
  }
  return shares.slice(0, count);
}

async function doSetup() {
  // A DEMO master key. In production this is the user's real provider key,
  // generated by the provider and pasted here once — same lifecycle.
  const demoKey = 'sk-demo-' + crypto.randomBytes(24).toString('hex');
  const keyBytes = Buffer.from(demoKey, 'utf8');
  const fp = fingerprint(demoKey);
  const shares = shamir.split(keyBytes, N_SHARES, THRESHOLD);
  const enc = shares.map(shamir.b64encode);

  fs.mkdirSync(path.dirname(VAULT_FILE), { recursive: true });
  fs.writeFileSync(VAULT_FILE, enc[0] + '\n', { mode: 0o600 });       // share 1: this machine
  fs.writeFileSync(BACKUP_FILE, enc[4] + '\n', { mode: 0o600 });      // share 5: "offline backup"
  const a = await call(`${COSIGNER_A_URL}/store-share`, 'POST', { share: enc[1] }, { 'x-cosigner-token': COSIGNER_TOKEN });
  const b = await call(`${COSIGNER_B_URL}/store-share`, 'POST', { share: enc[2] }, { 'x-cosigner-token': COSIGNER_TOKEN });
  if (a.status !== 200 || b.status !== 200) throw new Error('a co-signer refused its share — is start.js running?');

  // Register with the (mock) provider which key fingerprint is valid.
  if (LLM_MODE === 'mock') await call(`${LLM_BASE_URL}/configure`, 'POST', { fingerprint: fp }).catch(() => {});

  const runId = 'run-' + Date.now().toString(36);
  state = { runId, keyFingerprint: fp, demoKeyPreview: demoKey.slice(0, 11) + '…' + demoKey.slice(-4), lastJobId: null };
  // demoKey goes out of scope here; the whole key no longer exists anywhere.
  return {
    ok: true,
    runId,
    keyFingerprint: fp,
    threshold: THRESHOLD,
    shares: N_SHARES,
    distribution: [
      'Share 1 (x=1) → local vault file on this machine',
      'Share 2 (x=2) → Co-signer A (separate process, holds only this share)',
      'Share 3 (x=3) → Co-signer B (separate process, holds only this share)',
      'Share 4 (x=4) → paper backup — shown once below, stored NOWHERE by the system',
      'Share 5 (x=5) → offline backup file (separate failure domain)',
    ],
    paperBackupShare: enc[3],
    note: 'The whole master key has been wiped. It now exists only as 5 shares; any 3 reconstruct it, any 2 reveal nothing.',
  };
}

async function doRun(prompt) {
  if (!state) throw new Error('run /api/setup first');
  const steps = [];
  const step = (name, detail) => steps.push({ name, detail });

  // 1. Reconstruct the master key in memory from 3 shares.
  const shares = await fetchShares(THRESHOLD);
  step('shares-fetched', `Fetched ${shares.length} shares (local vault + co-signer A + co-signer B). No single holder had the key.`);
  const masterKey = shamir.combine(shares);
  const masterKeyStr = masterKey.toString('utf8');
  if (fingerprint(masterKeyStr) !== state.keyFingerprint) throw new Error('reconstruction fingerprint mismatch — shares do not belong to this key');
  step('key-reconstructed', `Master key rebuilt in memory only and verified by SHA-256 fingerprint ${state.keyFingerprint}. It is never written to disk or sent to the host.`);

  // 2. Encrypt the prompt locally; hand the HOST only ciphertext.
  const sessionKey = deriveSessionKey(masterKey, state.runId);
  const promptBlob = encryptString(sessionKey, prompt);
  const jobRes = await call(`${HOST_URL}/jobs`, 'POST', { promptBlob, meta: { runId: state.runId, track: 'ai-pipeline' } });
  if (jobRes.status !== 201) throw new Error('host refused the job');
  const jobId = jobRes.json.jobId;
  state.lastJobId = jobId;
  step('job-to-host', `Host received job ${jobId}: AES-256-GCM ciphertext (sha256:${fingerprint(promptBlob.ct)}), metadata only otherwise. The host cannot read the prompt.`);

  // 3. Call the LLM provider DIRECTLY from local — host is not in this path.
  const llmRes = await call(`${LLM_BASE_URL}/chat/completions`, 'POST', {
    model: LLM_MODEL,
    messages: [{ role: 'user', content: prompt }],
  }, { authorization: `Bearer ${masterKeyStr}` });
  if (llmRes.status !== 200) throw new Error(`LLM provider rejected the call (HTTP ${llmRes.status})`);
  const completion = llmRes.json.choices[0].message.content;
  step('llm-called-directly', `${LLM_MODE === 'mock' ? 'Mock provider' : 'Provider'} answered a direct local→provider call. The host was not a party to it and saw neither key nor prompt.`);

  // 4. Encrypt the response; the host stores it as agent memory (ciphertext).
  const responseBlob = encryptString(sessionKey, completion);
  await call(`${HOST_URL}/jobs/${jobId}/artifact`, 'POST', { responseBlob });
  step('artifact-stored', `Response encrypted and stored ON THE HOST as agent memory — as ciphertext (sha256:${fingerprint(responseBlob.ct)}). A host breach leaks ciphertext, not conversations.`);

  // 5. Retrieve + decrypt locally.
  const stored = await call(`${HOST_URL}/jobs/${jobId}`, 'GET');
  const recovered = decryptString(sessionKey, stored.json.responseBlob);
  step('decrypted-locally', 'Artifact fetched back and decrypted here, on your machine, with the locally derived session key.');

  masterKey.fill(0); // wipe
  return { ok: true, jobId, steps, response: recovered };
}

async function attackUnderThreshold() {
  if (!state || !state.lastJobId) throw new Error('complete a run first');
  const shares = await fetchShares(THRESHOLD - 1); // only 2 shares
  // Interpolating 2 points yields SOME byte string — but with threshold 3,
  // every possible secret is equally consistent with these 2 shares, so
  // this "reconstruction" is a guess that is wrong with probability ~1.
  const guessedKey = shamir.combine(shares);
  // Fingerprint the RAW guessed bytes (the real key's fingerprint is over
  // its UTF-8 bytes, so this is an apples-to-apples comparison).
  const fpMatch = fingerprint(guessedKey) === state.keyFingerprint;
  const stored = await call(`${HOST_URL}/jobs/${state.lastJobId}`, 'GET');
  let decryptResult;
  try {
    decryptString(deriveSessionKey(guessedKey, state.runId), stored.json.responseBlob);
    decryptResult = 'decrypted?! (unexpected)';
  } catch {
    decryptResult = 'AES-256-GCM authentication FAILED — wrong key, ciphertext rejected';
  }
  // The guessed bytes are arbitrary binary; present them hex-encoded as
  // the bearer key — still simply the wrong key, and the provider says so.
  const llmRes = await call(`${LLM_BASE_URL}/chat/completions`, 'POST', {
    model: LLM_MODEL, messages: [{ role: 'user', content: 'attack probe' }],
  }, { authorization: `Bearer ${guessedKey.toString('hex')}` });
  guessedKey.fill(0);
  return {
    ok: true,
    sharesUsed: THRESHOLD - 1,
    threshold: THRESHOLD,
    fingerprintMatch: fpMatch,
    decryptAttempt: decryptResult,
    llmAttempt: `provider returned HTTP ${llmRes.status} for the guessed key`,
    conclusion: 'Two shares are mathematically consistent with every possible key, so the guess is worthless: it fails the fingerprint check, fails GCM decryption, and is rejected by the provider.',
  };
}

async function attackTamper() {
  if (!state || !state.lastJobId) throw new Error('complete a run first');
  const shares = await fetchShares(THRESHOLD);
  const masterKey = shamir.combine(shares);
  const sessionKey = deriveSessionKey(masterKey, state.runId);
  const stored = await call(`${HOST_URL}/jobs/${state.lastJobId}`, 'GET');
  const blob = JSON.parse(JSON.stringify(stored.json.responseBlob));
  const raw = Buffer.from(blob.ct, 'base64');
  raw[0] ^= 0xff; // flip every bit of the first ciphertext byte
  blob.ct = raw.toString('base64');
  let result;
  try {
    decryptString(sessionKey, blob);
    result = 'decrypted?! (unexpected)';
  } catch {
    result = 'AES-256-GCM authentication FAILED — a single flipped byte invalidates the whole artifact';
  }
  masterKey.fill(0);
  return { ok: true, tamper: 'flipped all bits of ciphertext byte 0 in the host-stored artifact', decryptAttempt: result };
}

const server = http.createServer(async (req, res) => {
  const send = (code, obj) => {
    res.writeHead(code, { 'content-type': 'application/json' });
    res.end(JSON.stringify(obj));
  };
  try {
    if (req.method === 'GET' && (req.url === '/' || req.url === '/index.html')) {
      res.writeHead(200, { 'content-type': 'text/html' });
      return res.end(fs.readFileSync(path.join(__dirname, 'public', 'index.html')));
    }
    if (req.method === 'POST' && req.url === '/api/setup') return send(200, await doSetup());
    if (req.method === 'POST' && req.url === '/api/run') {
      let body = '';
      req.on('data', (c) => (body += c));
      req.on('end', async () => {
        try {
          const { prompt } = JSON.parse(body || '{}');
          if (!prompt) return send(400, { error: 'prompt required' });
          send(200, await doRun(prompt));
        } catch (e) { send(500, { error: e.message }); }
      });
      return;
    }
    if (req.method === 'POST' && req.url === '/api/attack/under-threshold') return send(200, await attackUnderThreshold());
    if (req.method === 'POST' && req.url === '/api/attack/tamper') return send(200, await attackTamper());
    if (req.method === 'GET' && req.url === '/api/host-view') {
      const hv = await call(`${HOST_URL}/host-view`, 'GET');
      return send(hv.status, hv.json);
    }
    if (req.method === 'GET' && req.url === '/api/status') return send(200, { ready: !!state, llmMode: LLM_MODE, ...(state || {}) });
    return send(404, { error: 'not found' });
  } catch (e) {
    return send(500, { error: e.message });
  }
});

if (require.main === module) {
  server.listen(PORT, '127.0.0.1', () => console.log(`[local] BlindRelay local agent UI on http://127.0.0.1:${PORT} (loopback only)`));
}

module.exports = { doSetup, doRun, attackUnderThreshold, attackTamper };
